/* حذف کلمات تکراری */
const uniqueWords = [...new Set(wordBank)];


/* مرتب‌سازی تقریبی بر اساس سختی */
const easyWords = uniqueWords.filter(w => w.length <= 4);
const mediumWords = uniqueWords.filter(w => w.length >= 5 && w.length <= 7);
const hardWords = uniqueWords.filter(w => w.length >= 8);


/* اگر بانک کلمات کم باشد، همه کلمات استفاده می‌شوند */
function getPool(level) {

  if (level <= 100) {
    return [...easyWords, ...mediumWords];
  }

  if (level <= 200) {
    return [...easyWords, ...mediumWords, ...mediumWords];
  }

  if (level <= 300) {
    return [...mediumWords, ...hardWords];
  }

  if (level <= 400) {
    return [...mediumWords, ...hardWords, ...hardWords];
  }

  return [...hardWords, ...mediumWords, ...uniqueWords];
}


/* انتخاب کلمات بدون تکرار در همان مرحله */
function makeLevel(level) {

  let count;

  if (level <= 100) {
    count = 4;
  } else if (level <= 200) {
    count = 5;
  } else if (level <= 300) {
    count = 6;
  } else if (level <= 400) {
    count = 7;
  } else {
    count = 8;
  }

  const pool = getPool(level);

  const result = [];
  const used = new Set();

  /*
    انتخاب چرخشی باعث می‌شود مرحله‌ها
    فقط یک کلمه را تکرار نکنند.
  */
  let start = (level * 13) % pool.length;

  for (let i = 0; i < pool.length && result.length < count; i++) {

    const word = pool[(start + i) % pool.length];

    if (!used.has(word)) {
      used.add(word);
      result.push(word);
    }
  }

  return result;
}


