function normalizePersianWord(word) {
    return String(word)
        .replace(/ي/g, "ی")
        .replace(/ى/g, "ی")
        .replace(/ك/g, "ک")
        .replace(/ۀ/g, "ه")
        .replace(/ة/g, "ه")
        .replace(/ؤ/g, "و")
        .replace(/إ/g, "ا")
        .replace(/أ/g, "ا")
        .replace(/ٱ/g, "ا")
        .replace(/‌/g, "")
        .replace(/\u200c/g, "")
        .replace(/\u200d/g, "")
        .replace(/\s+/g, "")
        .trim();
}

