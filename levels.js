const uniqueWords = [...new Set(
  wordBank
    .map(w => String(w).trim())
    .filter(w => w.length >= 2)
)];

/* ======================================================
   دسته‌بندی سختی
====================================================== */

const easyWords = uniqueWords.filter(w =>
  w.length >= 2 && w.length <= 4
);

const mediumWords = uniqueWords.filter(w =>
  w.length >= 4 && w.length <= 6
);

const hardWords = uniqueWords.filter(w =>
  w.length >= 5
);

/* ======================================================
   امتیاز سختی کلمه
====================================================== */

function wordDifficulty(word){

  let score = word.length * 2;

  const difficultChars =
    "ژظضذثصطغق";

  for(const ch of word){

    if(difficultChars.includes(ch)){
      score += 2;
    }
  }

  if(new Set([...word]).size < word.length){
    score += 2;
  }

  return score;
}

/* ======================================================
   انتخاب کلمه‌ها
====================================================== */

function getPool(level){

  if(level <= 100)
    return easyWords;

  if(level <= 300)
    return mediumWords;

  return hardWords.length >= 20
    ? hardWords
    : mediumWords;
}

/* ======================================================
   چک کردن سختی مرحله
====================================================== */

function validStage(words){

  if(!Array.isArray(words))
    return false;

  if(words.length < 4)
    return false;

  const set = new Set(words);

  if(set.size !== words.length)
    return false;

  return true;
}

/* ======================================================
   ساخت مرحله
====================================================== */

function makeLevel(level){

  let amount;

  if(level <= 100){
    amount = 4;
  }else if(level <= 200){
    amount = 5;
  }else if(level <= 300){
    amount = 6;
  }else if(level <= 400){
    amount = 7;
  }else{
    amount = 8;
  }

  const pool = getPool(level);

  const result = [];

  /*
    seed ثابت باعث می‌شود هر بار
    مرحله‌ها یکسان بمانند.
  */

  let seed =
    (level * 7919) %
    Math.max(pool.length,1);

  let attempts = 0;

  while(
    result.length < amount &&
    attempts < pool.length * 3
  ){

    const index =
      (seed + attempts * 37 + level * 11)
      % pool.length;

    const word = pool[index];

    if(
      word &&
      !result.includes(word)
    ){

      result.push(word);
    }

    attempts++;
  }

  /*
    اگر به تعداد لازم نرسید،
    از بانک عمومی پر می‌شود.
  */

  if(result.length < amount){

    for(const word of uniqueWords){

      if(
        !result.includes(word)
      ){
        result.push(word);
      }

      if(result.length >= amount)
        break;
    }
  }

  return result.slice(0,amount);
}

