/* ---------------------------------------------------------
   پاک‌سازی بانک
--------------------------------------------------------- */

const CLEAN_WORD_BANK = [...new Set(
    WORD_BANK
        .map(normalizePersianWord)
        .filter(word => word.length >= 2)
)];

/* ---------------------------------------------------------
   تابع تعداد کلمات مرحله
--------------------------------------------------------- */

function getWordCount(level) {

    if (level <= 100) {
        return 4;
    }

    if (level <= 200) {
        return 5;
    }

    if (level <= 300) {
        return 6;
    }

    if (level <= 400) {
        return 7;
    }

    return 8;
}

/* ---------------------------------------------------------
   سختی مرحله
--------------------------------------------------------- */

function getDifficulty(level) {

    if (level <= 100) {
        return "آسان";
    }

    if (level <= 300) {
        return "متوسط";
    }

    if (level <= 500) {
        return "سخت";
    }

    if (level <= 800) {
        return "خیلی سخت";
    }

    if (level <= 1000) {
        return "حرفه‌ای";
    }

    return "افسانه‌ای";
}

/* ---------------------------------------------------------
   طول حداقل کلمات
--------------------------------------------------------- */

function getMinimumLength(level) {

    if (level <= 100) {
        return 2;
    }

    if (level <= 300) {
        return 3;
    }

    if (level <= 500) {
        return 3;
    }

    if (level <= 700) {
        return 3;
    }

    if (level <= 900) {
        return 4;
    }

    if (level <= 1050) {
        return 4;
    }

    return 5;
}

/* ---------------------------------------------------------
   حروف یک کلمه
--------------------------------------------------------- */

function getLetters(word) {
    return [...normalizePersianWord(word)];
}

/* ---------------------------------------------------------
   امتیاز شباهت کلمات
--------------------------------------------------------- */

function wordSimilarity(a, b) {

    const aa = new Set(getLetters(a));
    const bb = new Set(getLetters(b));

    let same = 0;

    aa.forEach(letter => {
        if (bb.has(letter)) {
            same++;
        }
    });

    return same;
}

/* ---------------------------------------------------------
   امتیاز تنوع حروف
--------------------------------------------------------- */

function levelLetterScore(words) {

    const letters = new Set();

    words.forEach(word => {
        getLetters(word).forEach(letter => {
            letters.add(letter);
        });
    });

    return letters.size;
}

/* ---------------------------------------------------------
   انتخاب کلمات مرحله
--------------------------------------------------------- */

function createLevel(level) {

    const count = getWordCount(level);
    const minLength = getMinimumLength(level);

    let candidates = CLEAN_WORD_BANK.filter(
        word => word.length >= minLength
    );

    /*
      برای مراحل بالا، کلمات طولانی‌تر اولویت دارند.
    */

    if (level >= 700) {

        const longWords = candidates.filter(
            word => word.length >= 5
        );

        if (longWords.length >= count) {
            candidates = longWords;
        }
    }

    if (level >= 1000) {

        const harderWords = candidates.filter(
            word => word.length >= 6
        );

        if (harderWords.length >= count) {
            candidates = harderWords;
        }
    }

    /*
      تعیین نقطه شروع به صورت قطعی.
      باعث می‌شود هر بار همان مراحل ساخته شوند.
    */

    const start =
        ((level * 37) + (level * level)) %
        candidates.length;

    let selected = [];

    /*
      کلمات را با فاصله انتخاب می‌کنیم تا مراحل
      تنوع بیشتری داشته باشند.
    */

    for (let i = 0; i < candidates.length && selected.length < count; i++) {

        const index =
            (start + i * 11 + level * 3) %
            candidates.length;

        const word = candidates[index];

        if (!selected.includes(word)) {
            selected.push(word);
        }
    }

    /*
      اگر به هر دلیل تعداد کافی نبود،
      از ابتدای بانک پر می‌کنیم.
    */

    if (selected.length < count) {

        for (const word of CLEAN_WORD_BANK) {

            if (!selected.includes(word)) {
                selected.push(word);
            }

            if (selected.length >= count) {
                break;
            }
        }
    }

    /*
      مرتب‌سازی مخصوص مراحل سخت‌تر.
      در مراحل بالا کلمات بلندتر جلوتر می‌آیند.
    */

    if (level >= 500) {

        selected.sort((a, b) => {

            if (b.length !== a.length) {
                return b.length - a.length;
            }

            return a.localeCompare(b, "fa");
        });
    }

    return selected.slice(0, count);
}

/* ---------------------------------------------------------
   ساخت تمام مراحل
--------------------------------------------------------- */

const KALAMEBAZ_LEVELS = {};

for (let level = 1; level <= TOTAL_LEVELS; level++) {

    KALAMEBAZ_LEVELS[level] = createLevel(level);
}

/* ---------------------------------------------------------
   اطلاعات تکمیلی مراحل
--------------------------------------------------------- */

const KALAMEBAZ_LEVEL_INFO = {};

for (let level = 1; level <= TOTAL_LEVELS; level++) {

    const words = KALAMEBAZ_LEVELS[level];

    KALAMEBAZ_LEVEL_INFO[level] = {

        level: level,

        words: words.length,

        difficulty: getDifficulty(level),

        minimumLength: getMinimumLength(level),

        letters: [
            ...new Set(
                words.flatMap(word => getLetters(word))
            )
        ]
    };
}

