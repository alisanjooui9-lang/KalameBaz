/* ---------------------------------------------------------
   بررسی سلامت فایل
--------------------------------------------------------- */

(function validateLevels() {

    const numbers = Object.keys(KALAMEBAZ_LEVELS)
        .map(Number)
        .sort((a, b) => a - b);

    if (numbers.length !== TOTAL_LEVELS) {

        console.error(
            "❌ تعداد مراحل اشتباه است:",
            numbers.length
        );

        return;
    }

    for (let level = 1; level <= TOTAL_LEVELS; level++) {

        const words = KALAMEBAZ_LEVELS[level];

        if (!Array.isArray(words)) {

            console.error(
                "❌ مرحله نامعتبر:",
                level
            );

            return;
        }

        const required = getWordCount(level);

        if (words.length !== required) {

            console.error(
                `❌ مرحله ${level}: انتظار ${required} کلمه، دریافت ${words.length}`
            );

            return;
        }

        const uniqueWords = new Set(words);

        if (uniqueWords.size !== words.length) {

            console.warn(
                `⚠️ کلمات تکراری در مرحله ${level}`
            );
        }
    }

    console.log(
        `✅ کلمه‌باز: ${TOTAL_LEVELS} مرحله با موفقیت ساخته شد.`
    );

})();

